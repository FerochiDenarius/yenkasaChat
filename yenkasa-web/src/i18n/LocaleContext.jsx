const LocaleContext = createContext(null);

export function LocaleProvider({ children }) {
  const [language, setLanguageState] = useState(getStoredLanguage);

  useEffect(() => {
    const definition = getLanguageDefinition(language);
    document.documentElement.lang = definition.code;
    document.documentElement.dir = definition.dir;
  }, [language]);

  const value = useMemo(() => {
    function t(key, fallback = key) {
      return translations[language]?.[key] || translations.en[key] || fallback;
    }

    function setLanguage(nextLanguage) {
      const normalized = normalizeLanguage(nextLanguage);
      window.localStorage.setItem(LANGUAGE_KEY, normalized);
      setLanguageState(normalized);
      window.dispatchEvent(new CustomEvent("yenkasa:language-changed", { detail: normalized }));
    }

    return {
      language,
      languageLabel: getLanguageDefinition(language).nativeLabel,
      languageDefinition: getLanguageDefinition(language),
      setLanguage,
      t,
    };
  }, [language]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) {
    throw new Error("useLocale must be used inside LocaleProvider");
  }
  return context;
}

export function getStoredLanguage() {
  return normalizeLanguage(window.localStorage.getItem(LANGUAGE_KEY));
}

export function normalizeLanguage(value) {
  const code = String(value || "en").trim().toLowerCase();
  return SUPPORTED_LANGUAGES.some((item) => item.code === code) ? code : "en";
}

export function getLanguageDefinition(value) {
  const code = normalizeLanguage(value);
  return SUPPORTED_LANGUAGES.find((item) => item.code === code) || SUPPORTED_LANGUAGES[0];
}
